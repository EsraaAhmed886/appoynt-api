// Importing Metadata type definitions from next package
import type { Metadata } from "next";
// Importing localFont loader from next/font/local package
import localFont from "next/font/local";
// Importing global styles configuration file
import "./globals.css";

// Configuring Geist Sans variable local font
const geist_sans = localFont({
  // Setting path to Geist Sans font source file
  src: "./fonts/GeistVF.woff",
  // Defining custom css variable name for styling
  variable: "--font-geist-sans",
  // Specifying font weight range configuration
  weight: "100 900",
});

// Configuring Geist Mono variable local font
const geist_mono = localFont({
  // Setting path to Geist Mono font source file
  src: "./fonts/GeistMonoVF.woff",
  // Defining custom css variable name for styling
  variable: "--font-geist-mono",
  // Specifying font weight range configuration
  weight: "100 900",
});

// Exporting Next.js page metadata object configuration
export const metadata: Metadata = {
  // Title of the web page
  title: "Appoynt Web",
  // Description metadata tag for SEO optimization
  description: "Generated by Appoynt Web setup",
};

// Declaring and exporting the RootLayout component function
export default function RootLayout({
  // Desugaring children property parameter from layout props
  children,
}: Readonly<{
  // Setting ReactNode type requirement for children node
  children: React.ReactNode;
}>) {
  // Returning the layout template structure
  return (
    // Top-level HTML template element setting English language code
    <html lang="en">
      {/* Root body element applying custom font variable classes */}
      <body
        // Dynamic className concatenation applying font styles and antialiasing
        className={`${geist_sans.variable} ${geist_mono.variable} antialiased`}
      >
        {/* Injecting children node content */}
        {children}
      </body>
    </html>
  );
}
